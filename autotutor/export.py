"""Write a lesson to disk: audio, study sheet, HTML with real furigana, subtitles."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from html import escape
from pathlib import Path
from typing import List, Optional, Sequence

from .levels import get_level
from .models import Lesson
from .tts.audio import UnsupportedFormat, write_clip
from .version import APP_NAME, __version__


@dataclass
class ExportResult:
    files: List[Path] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return bool(self.files)


# --------------------------------------------------------------------------
# Audio
# --------------------------------------------------------------------------


def export_audio(clip, directory: Path, stem: str, bitrate: int = 128,
                 fmt: str = "mp3") -> Path:
    """Write ``clip`` as ``<stem>.<fmt>`` inside ``directory``."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    return write_clip(clip, directory / f"{stem}.{fmt.lower().lstrip('.')}", bitrate)


# --------------------------------------------------------------------------
# Text
# --------------------------------------------------------------------------


def lesson_to_text(lesson: Lesson) -> str:
    level = get_level(lesson.level)
    lines: List[str] = []
    title = lesson.title_ja or lesson.topic_label
    lines.append(f"{title}".strip())
    if lesson.title_zh:
        lines.append(lesson.title_zh)
    lines.append("=" * 46)
    lines.append(f"级别 Level : {level.code}（{level.label_zh} / {level.label_en}）")
    lines.append(f"主题 Topic : {lesson.topic_label or lesson.topic}")
    lines.append(f"来源 Source: {lesson.source_label or lesson.source}")
    if lesson.source_url:
        lines.append(f"           {lesson.source_url}")
    lines.append(f"生成时间   : {lesson.created_at}")
    lines.append(f"预计时长   : 约 {lesson.estimated_seconds} 秒")
    lines.append("")

    lines.append("【日本語（ふりがな付き）】")
    for index, sentence in enumerate(lesson.sentences, 1):
        lines.append(f"{index:2d}. {sentence.furigana_inline}")
    lines.append("")

    lines.append("【かな だけ / 仅假名】")
    for index, sentence in enumerate(lesson.sentences, 1):
        lines.append(f"{index:2d}. {sentence.kana or sentence.ja}")
    lines.append("")

    if any(s.zh for s in lesson.sentences):
        lines.append("【中文翻译】")
        for index, sentence in enumerate(lesson.sentences, 1):
            lines.append(f"{index:2d}. {sentence.zh}")
        lines.append("")

    if lesson.vocab:
        lines.append("【単語 / 生词】")
        for entry in lesson.vocab:
            kana = f"（{entry.kana}）" if entry.kana and entry.kana != entry.word else ""
            lines.append(f"  {entry.word}{kana}  {entry.zh}")
        lines.append("")

    if lesson.warnings:
        lines.append("【提示】")
        for warning in lesson.warnings:
            lines.append(f"  * {warning}")
        lines.append("")

    lines.append(f"-- generated by {APP_NAME} {__version__}")
    return "\n".join(lines)


def export_text(lesson: Lesson, directory: Path, stem: str) -> Path:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{stem}.txt"
    path.write_text(lesson_to_text(lesson), encoding="utf-8")
    return path


