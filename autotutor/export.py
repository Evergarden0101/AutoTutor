def lesson_to_html(lesson: Lesson) -> str:
    level = get_level(lesson.level)
    items: List[str] = []
    for sentence in lesson.sentences:
        block = [f'  <li><div class="ja">{sentence.html_ruby}</div>']
        if sentence.zh:
            block.append(f'      <div class="zh">{escape(sentence.zh)}</div>')
        block.append("  </li>")
        items.append("\n".join(block))

    meta_parts = [
        f"<span>级别 {escape(level.code)}（{escape(level.label_zh)}）</span>",
        f"<span>主题 {escape(lesson.topic_label or lesson.topic)}</span>",
        f"<span>约 {lesson.estimated_seconds} 秒</span>",
    ]
    if lesson.source_label:
        if lesson.source_url:
            meta_parts.append(
                f'<span>来源 <a href="{escape(lesson.source_url)}">'
                f"{escape(lesson.source_label)}</a></span>"
            )
        else:
            meta_parts.append(f"<span>来源 {escape(lesson.source_label)}</span>")

    vocab_html = ""
    if lesson.vocab:
        rows = "\n".join(
            f"    <tr><td>{escape(v.word)}</td><td>{escape(v.kana)}</td>"
            f"<td>{escape(v.zh)}</td></tr>"
            for v in lesson.vocab
        )
        vocab_html = (
            '<section class="vocab"><h2 style="font-size:1.05rem">単語 / 生词</h2>\n'
            f"  <table>\n{rows}\n  </table>\n</section>"
        )

    notes_html = ""
    if lesson.warnings:
        notes = "".join(f"<li>{escape(w)}</li>" for w in lesson.warnings)
        notes_html = f'<div class="notes"><ul>{notes}</ul></div>'

    return _HTML_TEMPLATE.format(
        title=escape(lesson.title_ja or lesson.topic_label or "AutoTutor"),
        subtitle=escape(lesson.title_zh or ""),
        meta="".join(meta_parts),
        items="\n".join(items),
        vocab=vocab_html,
        notes=notes_html,
        app=APP_NAME,
        version=__version__,
        created=escape(lesson.created_at),
    )


def export_html(lesson: Lesson, directory: Path, stem: str) -> Path:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{stem}.html"
    path.write_text(lesson_to_html(lesson), encoding="utf-8")
    return path


