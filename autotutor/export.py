def _srt_timestamp(seconds: float) -> str:
    if seconds < 0:
        seconds = 0.0
    millis = int(round(seconds * 1000))
    hours, millis = divmod(millis, 3_600_000)
    minutes, millis = divmod(millis, 60_000)
    secs, millis = divmod(millis, 1000)
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{millis:03d}"


def lesson_to_srt(lesson: Lesson, timings: Sequence) -> str:
    blocks: List[str] = []
    for order, timing in enumerate(timings, 1):
        if timing.index >= len(lesson.sentences):
            continue
        sentence = lesson.sentences[timing.index]
        text = sentence.ja
        if sentence.zh:
            text += "\n" + sentence.zh
        blocks.append(
            f"{order}\n"
            f"{_srt_timestamp(timing.start)} --> {_srt_timestamp(timing.end)}\n"
            f"{text}\n"
        )
    return "\n".join(blocks)


def export_srt(lesson: Lesson, timings: Sequence, directory: Path, stem: str) -> Path:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{stem}.srt"
    path.write_text(lesson_to_srt(lesson, timings), encoding="utf-8")
    return path


# --------------------------------------------------------------------------
# JSON (re-openable inside the app)
# --------------------------------------------------------------------------


def export_json(lesson: Lesson, directory: Path, stem: str) -> Path:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{stem}.json"
    path.write_text(
        json.dumps(lesson.to_dict(), ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return path


# --------------------------------------------------------------------------
# Bundle
# --------------------------------------------------------------------------


def export_bundle(
    lesson: Lesson,
    directory: Path,
    *,
    clip=None,
    timings: Optional[Sequence] = None,
    stem: str = "",
    audio_format: str = "mp3",
    bitrate: int = 128,
    include_text: bool = True,
    include_html: bool = True,
    include_srt: bool = True,
    include_json: bool = False,
) -> ExportResult:
    """Export everything the learner asked for in one go."""
    result = ExportResult()
    directory = Path(directory)
    stem = stem or lesson.slug()

    if clip is not None:
        try:
            result.files.append(export_audio(clip, directory, stem, bitrate, audio_format))
        except UnsupportedFormat as exc:
            result.warnings.append(str(exc))
            try:
                result.files.append(export_audio(clip, directory, stem, bitrate, "mp3"))
            except Exception as inner:  # pragma: no cover - defensive
                result.warnings.append(f"音频导出失败：{inner}")
        except Exception as exc:  # pragma: no cover - defensive
            result.warnings.append(f"音频导出失败：{exc}")

    if include_text:
        result.files.append(export_text(lesson, directory, stem))
    if include_html:
        result.files.append(export_html(lesson, directory, stem))
    if include_json:
        result.files.append(export_json(lesson, directory, stem))
    if include_srt:
        if timings:
            result.files.append(export_srt(lesson, timings, directory, stem))
        else:
            result.warnings.append("当前音频无法计算逐句时间轴，已跳过字幕文件。")

    return result
